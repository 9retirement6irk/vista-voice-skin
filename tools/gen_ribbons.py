#!/usr/bin/env python3
"""Turn art/vista-ribbons.svg into src/.../RibbonData.java.

The skin draws the same animated ribbons as the Vista Aero Home Assistant
theme, natively, because Android has no SVG renderer. This reads the
handful of SVG features that file uses (skewed rays, cubic ribbon paths in
two swaying groups, travelling pulses, elliptical flares, linear and radial
gradients) and writes them out as Java data. Run it after editing the SVG:

    python3 tools/gen_ribbons.py
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SVG = ROOT / 'art' / 'vista-ribbons.svg'
OUT = ROOT / 'src' / 'me' / 'wxcyber' / 'kiosk' / 'vista' / 'RibbonData.java'
NS = '{http://www.w3.org/2000/svg}'


def f(value):
    text = repr(float(value))
    return (text[:-2] if text.endswith('.0') else text) + 'f'


def argb(color, opacity):
    color = color.lstrip('#')
    if len(color) == 3:
        color = ''.join(c * 2 for c in color)
    a = max(0, min(255, round(float(opacity) * 255)))
    return '0x%02X%s' % (a, color.upper())


def style_of(node):
    result = {}
    for part in (node.get('style') or '').split(';'):
        if ':' in part:
            key, value = part.split(':', 1)
            result[key.strip()] = value.strip()
    return result


def seconds(value, default):
    if value is None:
        return default
    value = value.strip()
    return float(value[:-2]) / 1000 if value.endswith('ms') else float(value.rstrip('s'))


def path_numbers(d):
    if not re.fullmatch(r'\s*M[^MCc]*(C[^MC]*)+\s*', d):
        raise SystemExit(f'Only "M x y C ..." paths are supported: {d[:40]}')
    return [float(n) for n in re.findall(r'-?\d+(?:\.\d+)?', d)]


def main():
    root = ET.parse(SVG).getroot()
    view = [float(v) for v in root.get('viewBox').split()]
    if view[:2] != [0, 0]:
        raise SystemExit('viewBox must start at 0 0')

    gradients = {}
    for grad in root.iter(NS + 'linearGradient'):
        stops = [(float(s.get('offset')), argb(s.get('stop-color'), s.get('stop-opacity', '1'))) for s in grad.iter(NS + 'stop')]
        user = grad.get('gradientUnits') == 'userSpaceOnUse'
        gradients[grad.get('id')] = ('linear', user, [float(grad.get(k, d)) for k, d in (('x1', 0), ('y1', 0), ('x2', 1), ('y2', 0))], stops)
    for grad in root.iter(NS + 'radialGradient'):
        stops = [(float(s.get('offset')), argb(s.get('stop-color'), s.get('stop-opacity', '1'))) for s in grad.iter(NS + 'stop')]
        gradients[grad.get('id')] = ('radial', False, [], stops)

    lines = []
    out = lines.append
    out('// SPDX-License-Identifier: Apache-2.0')
    out('// Generated by tools/gen_ribbons.py from art/vista-ribbons.svg. Do not edit by hand.')
    out('package me.wxcyber.kiosk.vista;')
    out('')
    out('/** The Vista Aero theme\'s ribbon wallpaper, in the SVG\'s own 2000 by 1250 user units. */')
    out('final class RibbonData {')
    out('    private RibbonData() {}')
    out('')
    out(f'    static final float VIEW_W = {f(view[2])}, VIEW_H = {f(view[3])};')
    out('')
    for gid, (kind, user, coords, stops) in sorted(gradients.items()):
        name = re.sub(r'(?<!^)(?=[A-Z])', '_', gid[1:] if gid.startswith('g') else gid).upper()
        out(f'    /** {gid}: {kind}{", user space" if user else ", object bounding box"}. */')
        if kind == 'linear':
            out(f'    static final float[] {name}_LINE = {{{", ".join(f(c) for c in coords)}}};')
        out(f'    static final float[] {name}_STOPS = {{{", ".join(f(o) for o, _ in stops)}}};')
        out(f'    static final int[] {name}_COLORS = {{{", ".join(c for _, c in stops)}}};')
    out('')

    rays, strokes, flares = [], [], []
    group_kind = {'sway': 'Ribbon.SWAY', 'sway2': 'Ribbon.SWAY2'}
    for node in root:
        tag = node.tag.replace(NS, '')
        if tag == 'rect' and 'ray' in (node.get('class') or ''):
            skew = re.fullmatch(r'skewX\((-?[\d.]+)\)', node.get('transform', 'skewX(0)'))
            st = style_of(node)
            rays.append(f'new Ribbon.Ray({f(node.get("x"))}, {f(node.get("y"))}, {f(node.get("width"))}, {f(node.get("height"))}, {f(skew.group(1))}, {f(seconds(st.get("animation-delay"), 0))}, {f(seconds(st.get("animation-duration"), 18))})')
        elif tag == 'g':
            kind = group_kind.get(node.get('class') or '', 'Ribbon.STILL')
            group_stroke = node.get('stroke')
            for path in node.iter(NS + 'path'):
                stroke = path.get('stroke', group_stroke)
                gradient = re.fullmatch(r'url\(#(\w+)\)', stroke or '')
                paint = f'"{gradient.group(1)}", 0' if gradient else f'null, {argb(stroke, 1)}'
                st = style_of(path)
                pulse = 'pulse' in (path.get('class') or '')
                timing = f'{f(seconds(st.get("animation-delay"), 0))}, {f(seconds(st.get("animation-duration"), 16))}' if pulse else '0f, 0f'
                numbers = ', '.join(f(n) for n in path_numbers(path.get('d')))
                strokes.append(f'new Ribbon.Stroke({kind}, {paint}, {f(path.get("stroke-width", 1))}, {f(path.get("opacity", 1))}, {"true" if pulse else "false"}, {timing}, new float[] {{{numbers}}})')
        elif tag == 'ellipse' and 'flare' in (node.get('class') or ''):
            st = style_of(node)
            flares.append(f'new Ribbon.Flare({f(node.get("cx"))}, {f(node.get("cy"))}, {f(node.get("rx"))}, {f(node.get("ry"))}, {f(seconds(st.get("animation-delay"), 0))}, {f(seconds(st.get("animation-duration"), 12))})')

    for name, items, kind in (('RAYS', rays, 'Ray'), ('STROKES', strokes, 'Stroke'), ('FLARES', flares, 'Flare')):
        out(f'    static final Ribbon.{kind}[] {name} = {{')
        for item in items:
            out(f'        {item},')
        out('    };')
    out('}')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUT.relative_to(ROOT)}: {len(rays)} rays, {len(strokes)} strokes, {len(flares)} flares')


if __name__ == '__main__':
    main()
